def ui_language():
    return _LANG


def set_language(lang):
    global _LANG
    _LANG = (lang or "en").lower()


def tr(key, lang=None):
    """Translate a UI label key (identity for English / unknown keys)."""
    lang = (lang or _LANG).lower()
    if lang == "zh":
        return ZH.get(key, key)
    return key
