def language_keys():
    """Key registry from the official English language file (help_define)."""
    keys = []
    if not os.path.exists(_EN_LANG_FILE):
        return keys
    try:
        text = open(_EN_LANG_FILE, encoding="latin-1",
                    errors="replace").read()
    except OSError:
        return keys
    for m in re.finditer(r'help_define\s+"([^"]+)"', text):
        key = m.group(1).strip()
        if key:
            keys.append(key)
    return keys

